import re
from pathlib import Path
import symox as sx
from symbolic import triangle_mean


def generate(path):
    r, s = sx.symbols("r s")
    basis = []
    for degree in range(5):
        for b in range(degree + 1):
            value = r ** (degree - b) * s**b
            for previous in basis:
                value = sx.expand(
                    value - triangle_mean(value * previous, r, s) * previous
                )
            basis.append(sx.expand(value / sx.sqrt(triangle_mean(value * value, r, s))))
    lines = [
        "// Generated by symbolic_gradient.py with Symox.",
        "__device__ inline void basis_gradient(double r, double s, double* dr, double* ds)",
        "{",
    ]
    for i, value in enumerate(basis):
        lines.append(f"#if NB > {i}")
        for name, variable in (("dr", r), ("ds", s)):
            code = re.sub(
                r"sqrt\((\d+)\)", r"sqrt(\1.0)", sx.ccode(sx.diff(value, variable))
            )
            lines.append(f"  {name}[{i}] = {code};")
        lines.append("#endif")
    lines.append("}")
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    generate(Path(__file__).with_name("basis_gradient.cuh"))
